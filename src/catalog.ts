// Normaliza termos para que a busca funcione com ou sem acentos nos dois idiomas.
export function normalizeSearch(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase()
    .trim();
}

export function matchesSearch(term: string, ...names: string[]): boolean {
  const normalizedTerm = normalizeSearch(term);
  return names.some((name) => normalizeSearch(name).includes(normalizedTerm));
}

// Limita valores numéricos aos intervalos que a interface aceita.
export function parseCount(
  value: string,
  min: number,
  max: number,
): number | null {
  if (!/^\d+$/.test(value.trim())) return null;
  const number = Number(value.trim());
  return Number.isInteger(number) && number >= min && number <= max
    ? number
    : null;
}
